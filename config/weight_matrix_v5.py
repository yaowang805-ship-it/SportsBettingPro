def kelly_075(actual_wr: float, avg_odds: float, bb_premium: float,
              n_bets: int = 100, cap: float = 0.06,
              sport_confidence: float = 1.0) -> float:
    """V5.2 ¾ Kelly仓位 (返回小数, 0.06 = 6%)。

    公式: kelly = max(0, wr×BB_odds - 1) / (BB_odds - 1) × KELLY_FRACTION × confidence(n) × sport_discount
    统一用 KELLY_FRACTION(0.50) 单一事实来源, 与 constants.py / bb_virtual_bet 一致
    (原 V5.2 曾误用 0.75, 2026-08-17 审查修正为 0.50)

    V4.4: 连续置信度 + 运动级折扣
      n >= 100: confidence = 1.0
      n >= 30:  confidence = 0.7 + 0.3×(n-30)/70  (线性插值 0.70→1.0)
      n >= 10:  confidence = 0.5 + 0.2×(n-10)/20  (线性插值 0.50→0.70)
      sport_confidence: NFL=0.75, NHL=0.75 (V5: 0.65→0.75, SBR 14K≥NFL 3K), 默认1.0
    """
    if actual_wr <= 0 or avg_odds <= 1.01:
        return 0.0
    bb_odds = avg_odds * (1.0 + bb_premium)
    roi = actual_wr * bb_odds - 1.0
    if roi <= 0:
        return 0.0
    from config.constants import KELLY_FRACTION  # 单一事实来源 (统一为 0.50)
    kelly = roi / (bb_odds - 1.0) * KELLY_FRACTION
    # V4.4: 连续样本量置信度 (替代4级阶梯)
    if n_bets >= 100:
        confidence = 1.0
    elif n_bets >= 30:
        confidence = 0.7 + 0.3 * (n_bets - 30) / 70.0
    elif n_bets >= 10:
        confidence = 0.5 + 0.2 * (n_bets - 10) / 20.0
    else:
        confidence = 0.5  # n<10 仍然 0.5, MIN_N 由调用者控制
    return min(cap, max(0.0, kelly * confidence * sport_confidence))  # V5.2: cap=0.06


