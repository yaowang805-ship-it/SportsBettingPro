def get_min_ev(sport: str, league: str, sub_market: str, odds: float) -> float:
    """最小 EV 门槛。stake>0 → 2%, stake=0 → 999。

    V4.5: Pin ROI全为负的盘口 → 提高EV门槛至5% (需BB高溢价覆盖).
    """
    sport_lower = (sport or "").lower()
    if sub_market in BLOCKED_MARKETS:
        return 999.0

    # V5.9: 分盘口门槛 — 职业标准: 直接盘 2%, 推导盘 3-4%。
    #   直接盘(1X2/HC/OU/corner): 2% — Pinnacle 历史数据驱动。
    #   推导 dc/dnb: 3% — 1X2推导(Shin无偏)略高于直接盘。
    #   推导 btts/oe + 特殊盘(correct_score/winning_margin/total_goals_range/first_to_score): 4%。
    #   推导 ht/ht_dc/ht_hc/ht_ou/ht_dnb/f5: 4% — Shin 已修 favorite-longshot 偏差, 不再需要 6% 压制。
    if sub_market in ("dc", "dnb"):
        base_min_ev = 3.0
    elif sub_market in ("btts", "oe", "correct_score", "winning_margin", "total_goals_range", "first_to_score"):
        base_min_ev = 4.0
    elif sub_market == "ht_dc":
        # 2026-08-29 薄锚降级: ht_dc「主/客」实际胜率42.7% vs 隐含53.4%(Pin半场盘口把平局
        # 定低 -11pt), 2% 门槛把假机会整天刷屏(8-28 推191条)。职业标准: 无可靠Pin锚点的
        # 盘口大幅提门槛(覆盖偏差), 等自有标定 n≥200 用真实胜率覆盖后再放开。
        base_min_ev = 12.0
    elif sub_market in ("ht", "ht_hc", "ht_ou", "ht_dnb", "f5"):
        # ht 独赢是强正 edge(中位CLV +6~14%/正率74%), 但仍按职业分档 <3% 不下注。
        base_min_ev = 3.0
    else:
        # 2026-08-29 职业分档对齐: <3% 一律不下注(原2%太松, 放行大量临场漂移假机会)。
        # 1x2/hc/ou 直接盘(Pin-sharp锚) 3% 起步, Kelly 再按 edge 定仓。
        base_min_ev = 3.0

    if sport_lower == "football":
        stake = get_kelly_stake_pct(sport, league, sub_market, odds)
        if stake > 0:
            return base_min_ev
        # V4.5: 赔率>10 → 按Wilson CI最差ROI逐bin放行
        if odds > 10.0:
            # Wilson最差ROI: bin26=-36% bin27=-40% bin28=-60% bin29=-57%
            if odds <= 11.0: return 41.0
            if odds <= 13.5: return 45.0
            if odds <= 17.5: return 65.0
            return 62.0  # >17.5
        return base_min_ev

    elif sport_lower == "tennis":
        return base_min_ev

    elif sport_lower == "basketball":
        stake = get_kelly_stake_pct(sport, league, sub_market, odds)
        if stake > 0:
            return base_min_ev
        if odds <= 8.0:
            return base_min_ev
        return 999.0

    elif sport_lower in ("baseball", "american_football"):
        return base_min_ev if odds < 5.0 else 999.0

    elif sport_lower in ("ice_hockey", "pingpong", "badminton", "volleyball"):
        return base_min_ev if odds < 3.0 else 999.0

    else:
        return base_min_ev


def get_odds_cap(sport: str, league: str, sub_market: str) -> float:
    """赔率上限。"""
    if sub_market in BLOCKED_MARKETS:
        return 0.0
    sport_lower = (sport or "").lower()

    if sport_lower == "football":
        return 20.0 if sub_market not in SPECIAL_MARKET_CAPS else SPECIAL_MARKET_CAPS[sub_market]["max_odds"]
    elif sport_lower == "tennis":
        for kw, cap in [("Masters",20.0),("Grand Slam",15.0),("ATP 500",15.0),
                        ("ATP 250",10.0),("WTA",10.0),("Challenger",8.0),("ITF",5.0)]:
            if kw.lower() in (league or "").lower():
                return cap
        return 8.0  # 未知赛事默认
    elif sport_lower == "basketball":
        return 8.0 if "NBA" in (league or "") else 5.0
    elif sport_lower in ("baseball", "american_football"):
        return 5.0
    elif sport_lower == "ice_hockey":
        return 5.0  # V4.3: SBR数据@4.0仍有正edge(n=60,+3%)
    elif sport_lower in ("mma", "boxing"):
        return 5.0  # V4.3: UFC 13,848笔@5.0仍有正edge (n=155)
    else:
        return 3.0


