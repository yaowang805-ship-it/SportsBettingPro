def _match_league(league: str, data_dict: dict):
    """匹配联赛数据: 精确 → 别名(中英文全称/简称)。不做子串模糊(会误配)。

    V5.7 铁律: 子串模糊会误配(Ukraine Premier League 含 "premier league" 错配成英超;
    "巴西乙级联赛" 含 "西乙" 错配成西乙), 一律删掉。匹配只靠精确 + 别名表。
    """
    if not league:
        return data_dict.get("_AGGREGATE")
    if league in data_dict:
        return data_dict[league]
    # 别名查找(中英文全称/简称 → V5键, 精确匹配)
    league_lower = league.lower().strip()
    if league_lower in _LEAGUE_ALIASES:
        cn_name = _LEAGUE_ALIASES[league_lower]
        if cn_name in data_dict:
            return data_dict[cn_name]
    return None  # 未知联赛返回 None, 触发 BTB 回退


def _match_market_data(market: str, league: str):
    """返回某盘口(hc/ou/dc/dnb/btts/oe/correct_score)的 OddsPortal 联赛数据, 回退 _AGGREGATE。"""
    md = ODDSPORTAL_MARKET_DATA.get(market, {})
    if not md:
        return None
    return _match_league(league, md)


def _kelly_from_market(market: str, league: str, idx: int, odds: float, confidence: float = 0.6):
    """用 OddsPortal 盘口数据算 Kelly。返回 stake 或 None(无数据/不可信)。"""
    om = _match_market_data(market, league)
    if not om:
        return None
    data = om.get(idx)
    if not data or data[2] < 20:
        return None
    wr, avg_o, n = data
    if wr * avg_o - 1 > 0.15:  # 收盘价胜率×均赔 >1.15 不可能, 说明样本噪声, 弃用
        return None
    bb_prem = _bb_premium_1x2(odds) * 0.95
    return kelly_075(wr, avg_o, bb_prem, n, sport_confidence=confidence) * get_oddsportal_discount(league)


